def main():
    skip_pip = "--no-pip" in sys.argv
    if not (HERE / "main.py").exists() or not (HERE / "static").is_dir():
        print("STOP: put update_to_v5.py inside your exam_buddy folder (the one that contains main.py and the static folder).")
        sys.exit(1)

    backup = HERE / ("backup_before_v5_" + datetime.now().strftime("%Y%m%d_%H%M%S"))
    written = []
    print("Updating Exam Buddy to version 5 ...")
    try:
        for rel, (digest, blob) in FILES.items():
            data = zlib.decompress(base64.b64decode(blob))
            if hashlib.sha256(data).hexdigest() != digest:
                raise RuntimeError("this updater file is damaged (" + rel + "). Download it again.")
            target = HERE / rel
            if target.exists():
                (backup / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(target, backup / rel)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            written.append(rel)
            print("  updated  %-24s %5.1f KB" % (rel, len(data) / 1024))
        for rel in written:
            if rel.endswith(".py"):
                py_compile.compile(str(HERE / rel), doraise=True, cfile=str(HERE / "__pycache__" / "_update_check.pyc"))
    except Exception as error:
        print("\nSOMETHING WENT WRONG: %s" % error)
        print("Putting your old files back ...")
        for rel in written:
            saved = backup / rel
            if saved.exists():
                shutil.copy2(saved, HERE / rel)
            elif (HERE / rel).exists():
                (HERE / rel).unlink()
        print("Done. Nothing was changed. Send me the message above.")
        sys.exit(1)

    if backup.exists():
        print("\nYour old files are saved in: %s" % backup.name)

    if not skip_pip:
        print("\nInstalling requirements (this can take a minute) ...")
        result = subprocess.run([sys.executable, "-m", "pip", "install", "-r", str(HERE / "requirements.txt")])
        if result.returncode != 0:
            print("The install did not finish. Run this yourself later:  python -m pip install -r requirements.txt")

    print("\nALL DONE. Next steps:")
    print("  1. Restart the server:   python -m uvicorn main:app --reload --port 8002")
    print("  2. In the browser press Ctrl + Shift + R")
    print("  3. Log in as admin -> Admin panel -> View documents -> click 'Test browser'")


if __name__ == "__main__":
    main()
